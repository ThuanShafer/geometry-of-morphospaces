export const FOUND_KEY = 'every-shell.found'

export function specimenById(id: string): Specimen | undefined {
  return SPECIMENS.find((specimen) => specimen.id === id)
}

export function matchSpecimen(params: RaupParams): Specimen | null {
  return SPECIMENS.find((specimen) => isMatch(params, specimen.params)) ?? null
}

export function nearestSpecimen(params: RaupParams): {
  specimen: Specimen
  warmth: number
  error: ReturnType<typeof axisError>
} {
  let best = SPECIMENS[0]
  let bestScore = Infinity
  for (const specimen of SPECIMENS) {
    const score = 1 - warmthOf(params, specimen.params)
    if (score < bestScore) {
      best = specimen
      bestScore = score
    }
  }
  return {
    specimen: best,
    warmth: warmthOf(params, best.params),
    error: axisError(params, best.params),
  }
}

export function inBounds(params: RaupParams): boolean {
  const logW = Math.log10(params.W)
  return logW >= LOG_W_MIN && logW <= LOG_W_MAX && params.D >= D_MIN && params.D <= D_MAX && params.T >= T_MIN && params.T <= T_MAX
}
